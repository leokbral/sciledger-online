	<article class="prose prose-lg max-w-none">
		<h1 class="text-4xl font-bold text-gray-900 mb-4">Publication Withdrawal Policy</h1>

		<div class="bg-indigo-50 border-l-4 border-indigo-500 p-4 mb-8">
			<p class="text-gray-700">
				This policy covers a different situation from withdrawing a submission. Here the
				<strong>editorial process is finished</strong>, the manuscript was reviewed and accepted, and
				the author decides not to go ahead with publication. Because the review work is already
				delivered, the settlement is not the same as withdrawing mid-process.
			</p>
		</div>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">When this policy applies</h2>
			<p class="text-gray-700 mb-4">
				It applies in the window between acceptance and publication:
			</p>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li><strong>From</strong> <code>accepted</code>, the editorial decision has been made and the manuscript has cleared peer review.</li>
				<li><strong>Also</strong> at <code>awaiting final decision</code> where the decision has effectively been settled and the manuscript is queued for publication.</li>
				<li><strong>Until</strong> the manuscript reaches <code>published</code>.</li>
			</ul>
			<div class="bg-amber-50 border border-amber-200 rounded-lg p-4 mt-4">
				<p class="text-gray-700">
					If your manuscript is still in <code>reviewer assignment</code>, <code>in review</code>,
					<code>needing corrections</code> or <code>under correction</code>, the
					<a href="/policies/submission-withdrawal" class="text-primary-600 hover:text-primary-700 font-semibold">Submission Withdrawal Policy</a>
					is the one that applies to you.
				</p>
			</div>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">How to request it</h2>
			<p class="text-gray-700 mb-4">
				After acceptance, the manuscript is being prepared for publication, so this request is handled
				by the editorial team rather than applied automatically.
			</p>
			<ol class="list-decimal list-inside space-y-2 text-gray-700 ml-4">
				<li>Contact <a href="/help/support" class="text-primary-600 hover:text-primary-700 font-semibold">Support</a> with the manuscript identifier.</li>
				<li>State that you are requesting withdrawal <strong>before publication</strong>, and give the reason.</li>
				<li>The editorial team confirms the manuscript's state and stops the publication step.</li>
			</ol>
			<p class="text-gray-700 mt-4">
				Requests are acted on as quickly as possible. Once an article has been published, this policy
				no longer applies, as explained in the last section.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">What happens to the manuscript</h2>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li>The publication step does not go ahead, and no DOI is issued for the article.</li>
				<li>The acceptance and the full editorial record are preserved. The manuscript was accepted, and that stays in its history.</li>
				<li>The manuscript is not deleted, and the withdrawal is not recorded as a rejection.</li>
				<li>Reviews delivered during the process remain attached to the record.</li>
			</ul>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Editorial services already delivered</h2>
			<p class="text-gray-700 mb-4">
				This is what makes withdrawal after acceptance different from withdrawal during review. By the
				time a manuscript is accepted, essentially all the editorial work has been carried out:
			</p>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li>reviewers were found, invited and assigned;</li>
				<li>peer review was completed;</li>
				<li>correction rounds, where they happened, were handled;</li>
				<li>an editorial decision was reached and recorded.</li>
			</ul>
			<div class="bg-white border border-gray-200 rounded-lg p-4 mt-4">
				<p class="text-gray-700 text-sm">
					These services were performed. The amounts corresponding to them remain due, and choosing
					not to publish afterwards does not undo them. A full refund is not the default outcome of a
					withdrawal at this stage.
				</p>
			</div>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Publication not carried out</h2>
			<p class="text-gray-700 mb-4">
				Publication itself is the one service that does not get delivered. Where the publication step is
				charged separately from submission and review, that amount corresponds to work that was not
				performed, and it is treated accordingly under the terms applicable to your manuscript:
			</p>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li>If it was never charged, no charge is made.</li>
				<li>If it was authorized but not captured, the authorization can be cancelled and the reserved amount released.</li>
				<li>If it was already captured, it corresponds to a service that was not delivered, and is assessed for refund under the applicable terms.</li>
			</ul>
			<p class="text-gray-700 mt-4">
				Where submission, review and publication are covered by a single fee rather than charged
				separately, the settlement identifies the part attributable to the publication step that did not
				take place, rather than treating the whole fee as refundable or as forfeited.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Reviewers</h2>
			<p class="text-gray-700">
				Reviewers who completed reviews for the manuscript delivered their work before acceptance. Their
				remuneration is handled under the reviewer remuneration policy and is not affected by the
				author's decision not to publish. Withdrawing before publication does not reverse a completed
				review or the compensation attached to it.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Legal rights</h2>
			<p class="text-gray-700 mb-4">
				Any statutory right of withdrawal that applies to your contract, such as the right of regret in
				article 49 of the Brazilian Consumer Protection Code where that law applies, is a separate
				matter from this editorial policy, exercised under the terms the law itself sets. It runs from
				contracting, not from acceptance, and it is unrelated to the review deadlines, the card
				authorization window, or the editorial deadlines that ran during your submission. This policy
				neither restricts nor extends it.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Articles that are already published</h2>
			<div class="bg-red-50 border-l-4 border-red-500 p-4">
				<p class="text-gray-700">
					This policy stops at publication. Once an article is <code>published</code> it is part of the
					scholarly record: it is citable, it may already have been cited, and it is not withdrawn on
					request. Concerns about a published article are handled through correction or retraction,
					under the applicable
					<a href="/policies/publishing-ethics" class="text-primary-600 hover:text-primary-700 font-semibold">publishing ethics</a>
					process, and are assessed on the integrity of the record rather than on the author's
					preference.
				</p>
			</div>
		</section>

		<div class="bg-gray-50 border-l-4 border-gray-400 p-4 mt-8">
			<h3 class="font-semibold text-gray-900 mb-2">Which policy applies to me?</h3>
			<p class="text-gray-700">
				Check your manuscript's current state in your workspace. Before acceptance, use the
				<a href="/policies/submission-withdrawal" class="text-primary-600 hover:text-primary-700 font-semibold">Submission Withdrawal Policy</a>.
				After acceptance and before publication, this one. After publication, neither applies, so contact
				<a href="/help/support" class="text-primary-600 hover:text-primary-700 font-semibold">Support</a>.
			</p>
		</div>
