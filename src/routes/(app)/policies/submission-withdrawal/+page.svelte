	<article class="prose prose-lg max-w-none">
		<h1 class="text-4xl font-bold text-gray-900 mb-4">Submission Withdrawal Policy</h1>

		<div class="bg-amber-50 border-l-4 border-amber-500 p-4 mb-8">
			<p class="text-gray-700">
				This policy covers an author who decides to <strong>withdraw a manuscript while it is still
				moving through the editorial process</strong>. It does not cover a manuscript that has already
				completed the editorial process, which is covered by the
				<a href="/policies/publication-withdrawal" class="text-primary-600 hover:text-primary-700 font-semibold">Publication Withdrawal Policy</a>,
				and it does not cover an article that is already published.
			</p>
		</div>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">When you can withdraw</h2>
			<p class="text-gray-700 mb-4">
				A withdrawal request can be made at any point before an editorial decision to accept the
				manuscript. In SciLedger the manuscript can be withdrawn directly from these states:
			</p>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li><code>draft</code>, not yet submitted</li>
				<li><code>reviewer assignment</code>, submitted, with reviewers not yet working</li>
				<li><code>in review</code>, reviewers are working on the manuscript</li>
				<li><code>needing corrections</code>, corrections were requested</li>
				<li><code>under correction</code>, you are revising the manuscript</li>
			</ul>
			<div class="bg-blue-50 border border-blue-200 rounded-lg p-4 mt-4">
				<p class="text-gray-700">
					In <code>under final review</code> and <code>awaiting final decision</code> the manuscript is
					with the editorial team for a decision. A withdrawal request at that point is handled by the
					editors rather than applied automatically, because a decision may already be in progress.
					Contact <a href="/help/support" class="text-primary-600 hover:text-primary-700 font-semibold">Support</a>
					and the editorial team will confirm how the request is processed.
				</p>
			</div>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">How to request a withdrawal</h2>
			<ol class="list-decimal list-inside space-y-2 text-gray-700 ml-4">
				<li>Open the manuscript in your workspace.</li>
				<li>Request the withdrawal, or contact <a href="/help/support" class="text-primary-600 hover:text-primary-700 font-semibold">Support</a> if the option is not available at the manuscript's current state.</li>
				<li>State the reason. This is recorded with the request and helps the editorial team settle what is owed.</li>
			</ol>
			<p class="text-gray-700 mt-4">
				Only the submitting author or a corresponding author can request a withdrawal. The request and
				the resulting state change are recorded in the manuscript's editorial history.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">What happens to the manuscript</h2>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li>The manuscript returns to <code>draft</code> and leaves the editorial queue.</li>
				<li>It is <strong>not deleted</strong>. It stays in your workspace with its files and history.</li>
				<li>Reviewers lose their active assignment for it, and pending review invitations stop.</li>
				<li>Reviews already submitted stay attached to the manuscript's record.</li>
				<li>Withdrawing is not a rejection, and it is not recorded as one.</li>
			</ul>
			<p class="text-gray-700 mt-4">
				You may submit the manuscript again later. A new submission starts a new editorial process,
				with the fees that apply to it at that time.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Services already performed and services not yet performed</h2>
			<p class="text-gray-700 mb-4">
				The settlement of a withdrawal is based on what was actually delivered up to the moment of the
				request, not on the calendar alone. The two are treated differently:
			</p>

			<div class="space-y-4">
				<div class="bg-white border border-gray-200 rounded-lg p-4">
					<h3 class="font-semibold text-gray-900 mb-2">Services already performed</h3>
					<p class="text-gray-700 text-sm">
						Editorial handling that has taken place and peer reviews that have been completed are
						delivered work. The amounts corresponding to them remain due, and reviewers are
						compensated for reviews they completed.
					</p>
				</div>

				<div class="bg-white border border-gray-200 rounded-lg p-4">
					<h3 class="font-semibold text-gray-900 mb-2">Services not yet performed</h3>
					<p class="text-gray-700 text-sm">
						Stages that had not started when you withdrew, such as reviews not carried out or
						publication not performed, are undelivered. Amounts corresponding to them may be refunded or not
						charged, under the terms applicable to your submission.
					</p>
				</div>

				<div class="bg-white border border-gray-200 rounded-lg p-4">
					<h3 class="font-semibold text-gray-900 mb-2">Partially performed</h3>
					<p class="text-gray-700 text-sm">
						Where a stage was under way but not finished, the settlement distinguishes the part that
						was delivered from the part that was not. The editorial record of which reviews were
						completed, and when, is what establishes the split.
					</p>
				</div>
			</div>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Payments</h2>
			<p class="text-gray-700 mb-4">
				What happens to a payment depends on the state it is in when you withdraw:
			</p>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li><strong>Not yet charged</strong>, no charge is made.</li>
				<li><strong>Authorized but not captured</strong>, the authorization can be cancelled, and the reserved amount is released by your bank. No funds were transferred.</li>
				<li><strong>Captured</strong>, the amount was charged. Whether any part is refunded is decided by what was delivered, as described above, and by the terms accepted at payment.</li>
			</ul>
			<div class="bg-amber-50 border border-amber-200 rounded-lg p-4 mt-4">
				<p class="text-gray-700">
					A withdrawal is not by itself a refund. It is a request to stop the editorial process; the
					financial settlement is assessed separately against the work delivered.
				</p>
			</div>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Reviewers</h2>
			<p class="text-gray-700 mb-4">
				Withdrawing while reviewers are involved does not undo the work they have already done. The
				system distinguishes three situations, and they are treated differently:
			</p>

			<div class="space-y-4">
				<div class="bg-green-50 border border-green-200 rounded-lg p-4">
					<h3 class="font-semibold text-gray-900 mb-2">A reviewer who completed a valid review</h3>
					<p class="text-gray-700 text-sm">
						The review was delivered. It is handled under the reviewer remuneration policy exactly as
						it would be if the manuscript had continued, and it is not cancelled by your withdrawal.
					</p>
				</div>

				<div class="bg-white border border-gray-200 rounded-lg p-4">
					<h3 class="font-semibold text-gray-900 mb-2">A reviewer who accepted but did not deliver</h3>
					<p class="text-gray-700 text-sm">
						Accepting an invitation is not a completed review. The assignment is closed as incomplete,
						and remuneration is not released as though the work had been carried out.
					</p>
				</div>

				<div class="bg-white border border-gray-200 rounded-lg p-4">
					<h3 class="font-semibold text-gray-900 mb-2">A reviewer who was invited but did not review</h3>
					<p class="text-gray-700 text-sm">
						A pending invitation is withdrawn. Being invited, on its own, does not generate a payment.
					</p>
				</div>
			</div>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Legal right of withdrawal</h2>
			<p class="text-gray-700 mb-4">
				Separately from this editorial policy, consumer law may give you a statutory right to withdraw
				from a contract entered into online, within a period counted from contracting. Under Brazilian
				law this is the right of regret in article 49 of the Consumer Protection Code, where that law
				applies to your contract.
			</p>
			<div class="bg-blue-50 border-l-4 border-blue-500 p-4">
				<p class="text-gray-700 mb-2">
					Two things this statutory period is <strong>not</strong>:
				</p>
				<ul class="list-disc list-inside space-y-1 text-gray-700 text-sm">
					<li>It is not a rule that everything becomes non-refundable once it expires.</li>
					<li>It is not a rule that everything is refundable while it is running, regardless of what was delivered.</li>
				</ul>
			</div>
			<p class="text-gray-700 mt-4">
				A statutory right, where it applies, is exercised under the terms the law itself sets. This
				policy does not restrict it and does not extend it.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Cancelling after the statutory period</h2>
			<p class="text-gray-700 mb-4">
				A voluntary cancellation requested after any statutory period has run is assessed the same way
				as any other withdrawal: against what was actually delivered. It is not treated as forfeiting
				everything, and it is not treated as automatically refundable. The assessment considers:
			</p>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li>which editorial services were executed and which were not;</li>
				<li>which reviews were completed and which were still pending;</li>
				<li>the amounts genuinely due for the work delivered;</li>
				<li>the contractual terms accepted when the payment was made.</li>
			</ul>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">Four different periods, often confused</h2>
			<p class="text-gray-700 mb-4">
				Several unrelated clocks run during a submission. They are separate, they start at different
				moments, and one does not imply another:
			</p>
			<div class="overflow-x-auto">
				<table class="min-w-full border border-gray-200 text-sm">
					<thead class="bg-gray-50">
						<tr>
							<th class="border border-gray-200 px-4 py-2 text-left font-semibold text-gray-900">Period</th>
							<th class="border border-gray-200 px-4 py-2 text-left font-semibold text-gray-900">What it governs</th>
						</tr>
					</thead>
					<tbody>
						<tr>
							<td class="border border-gray-200 px-4 py-2 font-medium text-gray-900">Statutory right of withdrawal</td>
							<td class="border border-gray-200 px-4 py-2 text-gray-700">A legal right over the contract, where consumer law applies. Set by law, not by SciLedger.</td>
						</tr>
						<tr>
							<td class="border border-gray-200 px-4 py-2 font-medium text-gray-900">Review deadline</td>
							<td class="border border-gray-200 px-4 py-2 text-gray-700">The time a reviewer has to deliver their review. Set per assignment by the editorial team.</td>
						</tr>
						<tr>
							<td class="border border-gray-200 px-4 py-2 font-medium text-gray-900">Card authorization window</td>
							<td class="border border-gray-200 px-4 py-2 text-gray-700">A technical limit from the card network on how long a reserved amount stays valid before it must be renewed or released. Nothing to do with refund rights.</td>
						</tr>
						<tr>
							<td class="border border-gray-200 px-4 py-2 font-medium text-gray-900">Editorial deadlines</td>
							<td class="border border-gray-200 px-4 py-2 text-gray-700">Time limits on editorial stages, such as the window to return corrections.</td>
						</tr>
					</tbody>
				</table>
			</div>
			<p class="text-gray-700 mt-4">
				Some of these happen to be a similar number of days. That is a coincidence, not a connection.
				The expiry of a card authorization, in particular, says nothing about whether a refund is due.
			</p>
		</section>

		<section class="mb-8">
			<h2 class="text-2xl font-semibold text-gray-900 mb-4">What this policy does not cover</h2>
			<ul class="list-disc list-inside space-y-2 text-gray-700 ml-4">
				<li>A manuscript that has completed the editorial process and been accepted, covered by the <a href="/policies/publication-withdrawal" class="text-primary-600 hover:text-primary-700 font-semibold">Publication Withdrawal Policy</a>.</li>
				<li>An article that is already published. Published articles are part of the scholarly record and are handled through correction or retraction, not withdrawal.</li>
			</ul>
		</section>

